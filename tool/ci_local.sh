#!/usr/bin/env bash
# **ما يفحصه المسارُ قبل أن يفحصَه.**
#
# ── لماذا هذا الملفّ ────────────────────────────────────────────────────────
#
# حمرّت CI خمسَ مرّاتٍ على شيفرةٍ قلتُ إنّها خضراءُ عندي — وكنتُ صادقاً في
# كلّ مرّة: شغّلتُ ما أذكره لا ما يشغّله المسار.
#
# **١)** `#564` و`#565`: ثلاثةُ تحذيراتٍ في راسمٍ بـ`mobile/tool/`. وكنتُ
#     شغّلتُ `flutter test` ولم أُعِد `flutter analyze` بعد كتابة الراسم.
#     **و`tool/` يُحلَّل كما `lib/`.**
#
# **٢)** `#567`–`#569`: اختبارُ قاعدةٍ يسأل عن عددٍ في بيانةٍ كانت تُسحب
#     سحبَ القرعة. مرّ عندي وسقط هناك على الشيفرة نفسِها.
#
# فالعلّةُ في الحالتين واحدةٌ في جذرها: **ما أقيسه أنا ليس ما يقيسه
# المسار**. وهذا السكربتُ يشغّل الثلاثَ المهمّاتِ بأوامرها كما هي في
# `.github/workflows/ci.yml` — لا مختصراً ولا مزيداً.
#
# **وما ليس فيه قصداً: الضوابطُ السالبة.** تلك تكسر الشيفرةَ عمداً، فمكانُها
# يدُ من يكتب الضمانةَ لا فحصٌ قبل الدفع.
#
#   tool/ci_local.sh
set -uo pipefail
cd "$(dirname "$0")/.."
export PATH=/opt/flutter/bin:$PATH

FAIL=0
step() {
  local name="$1"; shift
  printf '\n\033[1m== %s ==\033[0m\n' "$name"
  if "$@"; then
    echo "✓ $name"
  else
    echo "✗ $name — سقط"; FAIL=$((FAIL+1))
  fi
}

# ── اللوحة ─────────────────────────────────────────────────────────────────
step "اللوحة — الاختبارات" npm test --silent
step "اللوحة — الأنواع والبناء" npm run build --silent

# ── التطبيق ────────────────────────────────────────────────────────────────
#
# **والتحليلُ قبل الاختبار كما في المسار.** وهو الذي سقط مرّتين، ويسقط
# على `tool/` كما يسقط على `lib/`.
step "التطبيق — التحليل" bash -c 'cd mobile && flutter analyze'
step "التطبيق — الاختبارات" bash -c 'cd mobile && flutter test'

# ── القاعدة ────────────────────────────────────────────────────────────────
step "القاعدة — اختبارات SQL" bash -c 'cd supabase/tests && npm test'

printf '\n'
if [ "$FAIL" = 0 ]; then
  echo "أخضرُ كلُّه — وهو ما سيراه المسار."
else
  echo "سقط $FAIL — ولا يُدفع قبل أن يخضرّ."
fi
[ "$FAIL" = 0 ]
