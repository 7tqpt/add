// تصديرُ تقارير CSV — `src/lib/csv.ts`.
//
// ── ولماذا يُحرَس ────────────────────────────────────────────────────────────
//
// هذه الدالّةُ تُخرج أسماءَ المزوّدين والعملاء ومبالغَ الحجوزات إلى ملفٍّ
// يفتحه صاحبُ المنصّة في Excel. **وما فيها ليس نصّاً من عندنا**: اسمُ القاعة
// يكتبه صاحبُها، وسببُ النزاع يكتبه عميل. فالحدُّ الفاصلُ هنا بين تقريرٍ
// سليمٍ وملفٍّ مكسورٍ خانةٌ فيها فاصلةٌ أو سطرٌ جديد.
//
// **والمقيسُ النصُّ الخارجُ لا الملفُّ المحفوظ.** الحفظُ يمرّ بالمتصفّح أو
// بحوار النظام في تطبيق سطح المكتب، وكلاهما خارجَ ما نملك. أمّا ما يُكتب
// فيه فهو هذا.
import { describe, expect, it } from 'vitest'

import { serialise, stampedFilename } from '../src/lib/csv'

describe('بنيةُ الملفّ', () => {
  it('**ويبدأ بعلامة ترتيب البايتات**', () => {
    // **وهي التي تجعل Excel يقرؤه UTF-8.** بدونها تصل العناوينُ العربيّةُ
    // وأسماءُ الناس حروفاً مشوّهة — وهو عيبٌ لا يظهر إلّا عند من يفتح الملفّ.
    const text = serialise({ columns: ['الاسم'], rows: [['قاعة التاج']] })
    expect(text.codePointAt(0)).toBe(0xfeff)
  })

  it('**والأسطرُ تُفصل بـCRLF** — وهو ما ينتظره Excel في كلّ نظام', () => {
    const text = serialise({ columns: ['أ', 'ب'], rows: [[1, 2]] })
    expect(text.slice(1)).toBe('أ,ب\r\n1,2')
  })

  it('والخانةُ الفارغةُ والغائبةُ تُكتبان فراغاً لا «null»', () => {
    const text = serialise({ columns: ['أ'], rows: [[null], [undefined], ['']] })
    expect(text.slice(1)).toBe('أ\r\n\r\n\r\n')
  })
})

describe('ما يكسر الملفّ إن لم يُحرَس', () => {
  it('**وفاصلةٌ لاتينيّةٌ في الاسم تُحاط بعلامتَي تنصيص**', () => {
    // ولولاها لَصار «Al Taj Hall, Sanaa» عمودين، وانزاح الجدولُ كلُّه.
    const text = serialise({ columns: ['الاسم'], rows: [['Al Taj Hall, Sanaa']] })
    expect(text.slice(1)).toBe('الاسم\r\n"Al Taj Hall, Sanaa"')
  })

  it('**والفاصلةُ العربيّةُ لا تُحاط — وهي ليست فاصلاً**', () => {
    // **ودرسٌ كتبتُه بإخفاقٍ:** كتبتُ «قاعة التاج، صنعاء» أوّلَ مرّة أحسبها
    // تكسر الملفّ، فسقط الاختبارُ والمنتجُ سليم. الفاصلةُ العربيّةُ `،`
    // (U+060C) حرفٌ كأيّ حرف، والفاصلُ في CSV هو `,` وحدَه.
    //
    // **وإحاطتُها كانت ستكون عيباً لا إصلاحاً:** أكثرُ أسماء المنصّة عربيّة،
    // فكلُّ اسمٍ فيه فاصلةٌ عربيّةٌ يخرج محاطاً بلا سبب.
    const text = serialise({ columns: ['الاسم'], rows: [['قاعة التاج، صنعاء']] })
    expect(text.slice(1)).toBe('الاسم\r\nقاعة التاج، صنعاء')
  })

  it('**وعلامةُ التنصيص تُضاعَف داخل الخانة**', () => {
    const text = serialise({ columns: ['الاسم'], rows: [['قاعة "التاج"']] })
    expect(text.slice(1)).toBe('الاسم\r\n"قاعة ""التاج"""')
  })

  it('**وسطرٌ جديدٌ في سبب النزاع لا يقطع الصفّ**', () => {
    // سببُ النزاع يكتبه عميلٌ في حقلٍ متعدّد الأسطر — وهو أشيعُ ما يقع.
    const text = serialise({ columns: ['السبب'], rows: [['لم يحضر\nوطلب المبلغ']] })
    expect(text.slice(1)).toBe('السبب\r\n"لم يحضر\nوطلب المبلغ"')
  })
})

describe('صيغُ Excel — وهي ثقبٌ لا عيبُ شكل', () => {
  // **والأسماءُ في هذه التقارير يكتبها المزوّدون والعملاء لا نحن.** فخانةٌ
  // تبدأ بـ`=` أو `+` أو `-` أو `@` يقرؤها Excel **صيغةً** ويُنفّذها حين
  // يفتح صاحبُ المنصّة التقرير. واختار (أ): شَرطةٌ مائلةٌ قبلها — وهي عُرفُ
  // Excel نفسِه ولا تظهر في الخانة.

  const cell = (value: string | number) =>
    serialise({ columns: ['x'], rows: [[value]] }).split('\r\n')[1]

  it('**واسمٌ يبدأ بـ`=` يُنزع فعلُه**', () => {
    // والإحاطةُ وحدَها **لا تمنع** التنفيذ — تمنع شطرَ العمود لا غير.
    expect(cell('=HYPERLINK("http://x","اضغط")')).toBe(
      '"\'=HYPERLINK(""http://x"",""اضغط"")"',
    )
  })

  it('**والثلاثةُ الباقيةُ مثلُه** — `+` و`-` و`@`', () => {
    expect(cell('@SUM(1+1)')).toBe("'@SUM(1+1)")
    expect(cell('+1234')).toBe("'+1234")
    expect(cell('-cmd')).toBe("'-cmd")
  })

  it('وجدولةٌ في الأوّل كذلك — ولا تُحاط', () => {
    // بعضُ النسخ تتخطّى الفراغَ البادئ ثمّ تقرأ ما بعده صيغةً.
    //
    // **ولا إحاطةَ هنا:** الجدولةُ ليست فاصلَ CSV — الفاصلُ `,` — فالإحاطةُ
    // زينةٌ لا يحتاجها الملفّ. كتبتُ الحدَّ محاطاً أوّلَ مرّة فسقط الاختبارُ
    // والمنتجُ سليم.
    expect(cell('\t=1+1')).toBe("'\t=1+1")
  })

  it('**والأسماءُ العاديّةُ لا تُمسّ** — ولا شَرطةَ في تقريرٍ عربيّ', () => {
    expect(cell('قاعة التاج')).toBe('قاعة التاج')
    expect(cell('Al Taj')).toBe('Al Taj')
    expect(cell('١٢٣')).toBe('١٢٣')
  })

  it('**والأرقامُ لا تُمسّ أبداً — وهذا هو بيتُ القصيد**', () => {
    // **ولولا فحصُ النوع لَانكسر كلُّ عمودٍ فيه مبلغٌ مردود.** ‏`-500`‏ خلف
    // شَرطةٍ يكفّ عن أن يكون رقماً: لا يُجمع العمود، ويخرج تقريرُ المرتجعات
    // بمجموعٍ صفرٍ بلا رسالةِ خطأٍ واحدة.
    expect(cell(-500)).toBe('-500')
    expect(cell(0)).toBe('0')
    expect(cell(1234.5)).toBe('1234.5')
  })
})

describe('اسمُ الملفّ', () => {
  it('يحمل تاريخَ اليوم وينتهي بـ‎.csv', () => {
    const name = stampedFilename('تقرير-المستخدمين')
    expect(name).toMatch(/^تقرير-المستخدمين-\d{4}-\d{2}-\d{2}\.csv$/)
  })
})
