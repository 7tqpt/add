// تنسيقُ الأرقام والتواريخ في لوحة التحكّم — `src/lib/format.ts`.
//
// ── ولماذا يبدأ الحرزُ من هنا ────────────────────────────────────────────────
//
// كانت اللوحةُ بلا اختبارٍ واحد، وهي التي تُوثّق المزوّدين وتُحرّك الأموال.
// وأوّلُ ما يُحرَس منها ليس أكبرَ ملفٍّ بل **أكثرُه انتشاراً**: هذه الدوالُّ
// تُنادى في كلّ صفحةٍ وكلّ بطاقةٍ وكلّ عمودِ جدول، وخطؤها يُقرأ رقماً خاطئاً
// عن المنصّة لا عطباً ظاهراً — فلا يصرخ أحد.
//
// **وهي دوالُّ خالصة**: دخلٌ وخرجٌ بلا شبكةٍ ولا شاشة. فتُقاس بلا تركيب.
//
// ── وما يُقاس هنا بعينه ──────────────────────────────────────────────────────
//
// **١) مطابقةُ العدد في العربيّة ليست جمعاً بالسين.** الاثنان لهما صيغةٌ
// تُسقط الرقم، والثلاثةُ إلى العشرة جمعُ قلّة، وما فوقها مفردٌ منصوب. و«٢ يوم»
// تُقرأ نصّاً مكسوراً لا اختيارَ تقريب.
//
// **٢) والمستقبلُ يُصاغ بـ«بعد» لا بـ«منذ».** وهو عيبٌ وقع فعلاً: الفرقُ
// سالبٌ فيقع تحت الدقيقة، فكانت دعوةٌ تنتهي بعد أسبوعٍ تُقرأ «الآن».
import { describe, expect, it, vi, afterEach } from 'vitest'

import {
  BOOKING_FORMS,
  DAY_FORMS,
  HOUR_FORMS,
  MINUTE_FORMS,
  formatCompact,
  formatCount,
  formatDelta,
  formatDuration,
  formatMoney,
  formatNumber,
  formatRelative,
  formatTime,
} from '../src/lib/format'

/**
 * يُجرَّد النصُّ من علامات الاتجاه غير المرئيّة قبل المقارنة.
 *
 * **ودرسٌ كُتب بخمسة إخفاقاتٍ في أوّل تشغيل:** `Intl.NumberFormat` في لغةٍ
 * عربيّةٍ يُقحم `U+200E` (علامةَ اليسار-إلى-اليمين) حول علامة النسبة وقبل
 * إشارة السالب — كي لا تنزلق في إعادة الترتيب ثنائيّ الاتجاه. فـ«‎12.4%‎»
 * ليست `'12.4%'` بايتاً ببايت، وهي هي على الشاشة.
 *
 * **ولا تُنزع من المنتج**: هي التي تُبقي «‎-1.2 ألف» على شكلها في سطرٍ
 * عربيّ. فتُنزع من **المقياس** وحدَه — والمقيسُ الأرقامُ والحروف لا
 * المحارفُ التي لا تُرى.
 */
const plain = (text: string) => text.replace(/[\u200e\u200f\u061c]/g, '')

describe('مطابقةُ العدد في العربيّة', () => {
  it('**والاثنان لهما صيغتُهما ويسقط الرقم**', () => {
    // «٢ يوم» نصٌّ مكسور، و«يومين» عربيّة.
    expect(formatCount(2, DAY_FORMS)).toBe('يومين')
    expect(formatCount(2, HOUR_FORMS)).toBe('ساعتين')
    expect(formatCount(2, BOOKING_FORMS)).toBe('حجزان')
  })

  it('والواحدُ يسقط رقمُه كذلك', () => {
    expect(formatCount(1, DAY_FORMS)).toBe('يوم')
    expect(formatCount(1, BOOKING_FORMS)).toBe('حجز واحد')
  })

  it('**ومن ثلاثةٍ إلى عشرةٍ جمعُ قلّة**', () => {
    expect(formatCount(3, DAY_FORMS)).toBe('3 أيام')
    expect(formatCount(10, DAY_FORMS)).toBe('10 أيام')
    expect(formatCount(7, HOUR_FORMS)).toBe('7 ساعات')
  })

  it('**وما فوق العشرة مفردٌ منصوب**', () => {
    expect(formatCount(11, DAY_FORMS)).toBe('11 يوماً')
    expect(formatCount(12, BOOKING_FORMS)).toBe('12 حجزاً')
    expect(formatCount(100, MINUTE_FORMS)).toBe('100 دقيقة')
  })

  it('والصفرُ يأخذ صيغةَ ما فوق العشرة', () => {
    // «0 يوماً» — وهي الصيغةُ العربيّة للصفر، لا «0 أيام».
    expect(formatCount(0, DAY_FORMS)).toBe('0 يوماً')
  })

  it('**والسالبُ يُطابَق بمقداره لا بإشارته**', () => {
    // ولولا `Math.abs` لَسقط كلُّ عددٍ سالبٍ في فرع «ما فوق العشرة».
    expect(formatCount(-2, DAY_FORMS)).toBe('يومين')
    expect(formatCount(-5, DAY_FORMS)).toBe('5 أيام')
  })
})

describe('الأرقام المختصرة', () => {
  it('دون الألف تُكتب كما هي', () => {
    expect(formatCompact(0)).toBe('0')
    expect(formatCompact(999)).toBe('999')
  })

  it('**ومن ألفٍ إلى عشرةِ آلافٍ بعشرٍ واحدة**', () => {
    expect(formatCompact(1000)).toBe('1.0 ألف')
    expect(formatCompact(1240)).toBe('1.2 ألف')
  })

  it('**وفوق عشرة آلافٍ تسقط العشر** — عمودُ محورٍ لا يتّسع لها', () => {
    expect(formatCompact(12_400)).toBe('12 ألف')
  })

  it('والمليونُ بحرفه', () => {
    expect(formatCompact(1_500_000)).toBe('1.5 م')
  })

  it('**والسالبُ يُختصر بمقداره ويحتفظ بإشارته**', () => {
    expect(plain(formatCompact(-1240))).toBe('-1.2 ألف')
  })
})

describe('المال', () => {
  it('**واللاحقةُ تُلحق باليد لا بـ`style: currency`**', () => {
    // رمزُ CLDR يحمل نقطةً أخيرةً تُقذف بإعادة الترتيب ثنائيّ الاتجاه إلى
    // طرف الرقم: «‎.145,873 ر.ي».
    expect(formatMoney(145_873)).toBe('145,873 ر.ي')
  })

  it('والصفرُ رقمٌ لا فراغ', () => {
    expect(formatMoney(0)).toBe('0 ر.ي')
  })

  it('والأرقامُ لاتينيّةٌ لا هنديّة', () => {
    // خيارٌ مقصود: تبقى مقروءةً إلى جانب أرقام النسخ ومحاور الرسوم.
    expect(formatNumber(1234)).toBe('1,234')
  })
})

describe('الفروق', () => {
  it('**والموجبُ يحمل علامةَ زائدٍ صريحة**', () => {
    expect(plain(formatDelta(0.124))).toBe('+12.4%')
  })

  it('**والسالبُ يحمل شَرطةَ الطرح لا الواصلة**', () => {
    // ‏`−`‏ (U+2212) لا `-`: الواصلةُ تُقرأ في سياقٍ عربيٍّ فاصلاً.
    expect(plain(formatDelta(-0.031))).toBe('−3.1%')
  })

  it('ولا إشارةَ للصفر', () => {
    expect(plain(formatDelta(0))).toBe('0%')
  })
})

describe('المدّة', () => {
  it('**وساعةٌ تامّةٌ لا تُتبع بصفر دقائق**', () => {
    expect(formatDuration(4 * 3600)).toBe('4 س')
  })

  it('وساعةٌ ودقائق', () => {
    expect(formatDuration(3720)).toBe('1 س 2 د')
  })

  it('ودقائقُ وحدَها، ثمّ ثوانٍ', () => {
    expect(formatDuration(120)).toBe('2 د')
    expect(formatDuration(45)).toBe('45 ث')
  })

  it('**وما ليس عدداً أو لا يقع يُقرأ شَرطةً لا صفراً**', () => {
    expect(formatDuration(0)).toBe('—')
    expect(formatDuration(-5)).toBe('—')
    expect(formatDuration(Number.NaN)).toBe('—')
    expect(formatDuration(Number.POSITIVE_INFINITY)).toBe('—')
  })
})

describe('الوقت', () => {
  it('**والظهرُ ١٢ ظهراً لا ٠ ظهراً**', () => {
    expect(formatTime('12:00')).toBe('12:00 م')
  })

  it('**ومنتصفُ الليل ١٢ صباحاً لا ٠ صباحاً**', () => {
    expect(formatTime('00:30')).toBe('12:30 ص')
  })

  it('والمساءُ يُحوَّل إلى اثنتي عشرة', () => {
    expect(formatTime('20:00')).toBe('8:00 م')
  })

  it('**وما لا يُقرأ يُعاد كما جاء لا يُخمَّن**', () => {
    expect(formatTime('صباحاً')).toBe('صباحاً')
    expect(formatTime(null)).toBe('—')
  })
})

describe('الزمنُ النسبيّ', () => {
  afterEach(() => vi.useRealTimers())

  const at = (iso: string) => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date(iso))
  }

  it('ما دون نصف الدقيقة «الآن»', () => {
    // **والحدُّ نصفُ دقيقةٍ لا دقيقة**، لأنّ الفرق يُقرَّب: ثلاثون ثانيةً
    // تُقرَّب إلى دقيقةٍ فتُقرأ «منذ دقيقة». وهو تقريبٌ مقصودٌ لا عطب —
    // كتبتُ الحدَّ خطأً أوّلَ مرّة فسقط الاختبارُ والمنتجُ سليم.
    at('2026-09-13T12:00:00Z')
    expect(formatRelative('2026-09-13T11:59:45Z')).toBe('الآن')
  })

  it('والساعاتُ والأيّامُ بصيغها', () => {
    at('2026-09-13T12:00:00Z')
    expect(formatRelative('2026-09-13T09:00:00Z')).toBe('منذ 3 ساعات')
    expect(formatRelative('2026-09-11T12:00:00Z')).toBe('منذ يومين')
  })

  it('**والمستقبلُ يُصاغ بـ«بعد» لا بـ«منذ»**', () => {
    // **وهذا عيبٌ وقع فعلاً:** الفرقُ سالبٌ فيقع تحت الدقيقة، فكانت دعوةٌ
    // تنتهي بعد أسبوعٍ تُقرأ «الآن».
    at('2026-09-13T12:00:00Z')
    expect(formatRelative('2026-09-20T12:00:00Z')).toBe('بعد 7 أيام')
    expect(formatRelative('2026-09-13T15:00:00Z')).toBe('بعد 3 ساعات')
  })

  it('**وما جاوز الشهر يُكتب تاريخاً** — «منذ 47 يوماً» لا يُقرأ', () => {
    at('2026-09-13T12:00:00Z')
    expect(formatRelative('2026-07-01T12:00:00Z')).toMatch(/2026/)
  })

  it('ولا تاريخَ يُخترع لمن لا تاريخَ له', () => {
    expect(formatRelative(null)).toBe('—')
  })
})
