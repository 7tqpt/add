-- ============================================================================
--  رابطُ تنزيل النسخة — ووصلُ حلقةٍ كانت مقطوعة
-- ============================================================================
--
-- جدولُ `app_versions` قائمٌ منذ أوّل مخطّط، وله شاشةٌ في اللوحة فيها نسبةُ
-- الطرح والتحديثُ الإجباريّ. **والتطبيق لا يقرؤه — ولا سطرٌ واحد.** فهو
-- صندوقٌ يُملأ ولا يُفتح: تُرفع فيه نسخةٌ ويُشعل «تحديث إجباريّ» فلا يقع
-- شيء، ولا يعلم صاحبُ الجوال أنّ نسخةً أحدثَ صدرت.
--
-- وينقصه عمودٌ واحدٌ ليصير نافعاً: **أين تُنزَّل**.
--
-- ── ولماذا يهمّ هذا هنا خاصّةً ───────────────────────────────────────────────
--
-- التوزيعُ اليومَ خارج المتاجر: حزمةٌ تُنشر في «إصدارات» المستودع وتُنزَّل
-- بالمتصفّح. ولا متجرَ يخبر الناسَ بالجديد، ولا خدمةَ تحديثٍ تلقائيّ. فمن
-- ثبّت حزمةً بقي عليها إلى الأبد ما لم يُخبَر — وأصحابُ النسخ القديمة يبقون
-- على عيوبٍ أُصلحت من شهور.
--
-- ── ولماذا `https` شرطاً في القاعدة لا في الشاشة ────────────────────────────
--
-- العمودُ يُقرأ في **تطبيق** يفتح ما فيه. ورابطٌ بمخطّطٍ آخر — `javascript:`
-- أو `intent:` أو `file:` — بابٌ يُفتح على الجهاز بما لا يُقصد. والشاشةُ
-- تُبدَّل وتُنسى، والقيدُ في القاعدة يبقى. ومن أراد لاحقاً `market://` لمتجر
-- Play يُوسَّع القيدُ عمداً بالتزامٍ يُقرأ، لا بثغرةٍ تُترك مفتوحة.
--
-- ولا يُشترط على الفارغ: نسخةٌ قديمةٌ لم يُسجَّل لها رابطٌ لا تُمنع من
-- البقاء في الجدول.
-- ============================================================================

alter table public.app_versions
  add column if not exists download_url text not null default '';

comment on column public.app_versions.download_url is
  'رابطُ تنزيل الحزمة — https وحده، ويُفتح في متصفّح الجهاز.';

alter table public.app_versions
  drop constraint if exists app_versions_download_url_https;

alter table public.app_versions
  add constraint app_versions_download_url_https
  check (download_url = '' or download_url ~ '^https://');

