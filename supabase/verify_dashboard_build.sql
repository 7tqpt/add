-- ============================================================================
--  أيُّ نسخةٍ من اللوحة هي التي أرسلت — من سجلّ العمليات
--
--  يقرأ ولا يغيّر شيئاً. وجملةٌ واحدة.
-- ============================================================================
--
--  ثبت بالقياس أنّ `api_admin_broadcast` تعمل: نُوديت من المحرّر فأعادت ٣
--  وكتبت ثلاثةَ صفوف. والمالكُ واحدٌ، ونصُّها نصُّ المستودع، والحرزُ لا
--  يُعميها. ومع ذلك سجّلت خمسُ حملاتٍ من اللوحة صفراً.
--
--  **فالنسخةُ التي تعمل في المتصفّح ليست نسخةَ المستودع.** وشيفرةُ اللوحة
--  قبل ٢٤ أغسطس كانت تكتب الصفَّ `status = 'sent'` عند إنشائه و`recipients`
--  صفراً، **ولا تنادي الدالّةَ أصلاً** — وهو ما نراه حرفاً بحرف.
--
--  ── والقاعدةُ تحفظ بصمةَ النسخة ───────────────────────────────────────────
--
--  كلتا النسختين تكتبان في `audit_log` عند الإرسال، وتفترقان في `details`:
--
--    · القديمة → { audience, scheduled_at }            — مفتاحان
--    · الجديدة → { audience, scheduled_at, recipients } — وفيه `recipients`
--
--  فوجودُ المفتاح أو غيابُه يقول أيُّ شيفرةٍ عملت — بلا فتح متصفّحٍ ولا
--  قراءةِ حزمة.
-- ============================================================================

select 1 as ت,
       to_char(a.created_at, 'MM-DD HH24:MI') as الوقت,
       coalesce(a.entity_label, '—') as الحملة,
       case when a.details ? 'recipients'
            then '✅ نسخةٌ حديثة — تنادي api_admin_broadcast (recipients: '
                 || coalesce(a.details ->> 'recipients', 'null') || ')'
            else '❌ **نسخةٌ قديمة** — تكتب «مُرسل» ولا تنادي الدالّة'
       end as النسخة
  from public.audit_log a
 where a.action = 'notification.send'

union all
select 2, '—', '— الحكم —',
       case
         when (select count(*) from public.audit_log
                where action = 'notification.send') = 0
           then '⚠️ لا سطرَ إرسالٍ في السجلّ — لم تُرسَل حملةٌ من اللوحة، أو السجلُّ فُرّغ.'
         when (select count(*) from public.audit_log
                where action = 'notification.send' and details ? 'recipients') = 0
           then '❌ **اللوحةُ التي في متصفّحك أقدمُ من ٢٤ أغسطس.** حدّث نشرَها (Netlify → Deploys → Trigger deploy) ثمّ أعد تحميل الصفحة تحميلاً قسريّاً (Ctrl+Shift+R).'
         else '✅ النسخةُ حديثةٌ — والعلّةُ في موضعٍ آخر.'
       end
order by ت, الوقت desc;
