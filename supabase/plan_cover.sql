-- ============================================================================
--  غلافُ خطّة العرس — صورةُ أوّل خدمةٍ حُجزت فيها
--
--  شغّله بعد `install.sql` و`service_media.sql`. آمنٌ عند التكرار.
-- ============================================================================
--
--  ── ما ينقص اليوم ─────────────────────────────────────────────────────────
--
--  بطاقةُ رأس «خطة العرس» أيقونةُ قلبٍ واحدةٌ لكلّ خطّة. واختار صاحبُ
--  المنصّة أن تصير صورةً، ومصدرُها **غلافُ أوّل خدمةٍ حجزها في هذه الخطّة**
--  — لا صورةً مرفقةً بالتطبيق واحدةً للجميع.
--
--  و`wedding_plans` لا تحمل عموداً لصورة، و`v_plan_summary` لا تعرف
--  الوسائط. والطريقُ إليها ثلاثُ قفزات:
--
--      bookings → provider_services → service_media
--
--  ── ولماذا دالّةٌ لا عمودٌ في الطريقة ─────────────────────────────────────
--
--  `v_plan_summary` طريقةٌ مجمَّعةٌ بـ`group by`، وإضافةُ عمودٍ إليها تعني
--  `drop view` ثمّ `create view` — وما يعتمد عليها يسقط معها. والدالّةُ
--  تأخذ معرّفَ الخطّة وتردّ سطراً واحداً، ولا تمسّ شيئاً قائماً.
--
--  ── وأيُّ حجزٍ هو «الأوّل» ─────────────────────────────────────────────────
--
--  **الأوّلُ بوقت الحجز لا بتاريخ العرس**: الخطّةُ الواحدةُ حجوزُها كلُّها في
--  يوم العرس نفسِه غالباً، فترتيبٌ بـ`event_date` يُخرج صفّاً غيرَ معيَّن
--  يتبدّل بين نداءٍ ونداء — وصورةٌ تتبدّل بلا سببٍ تُقرأ عطباً.
--
--  والملغى والمرفوضُ خارج الحساب كما في `v_plan_summary` حرفاً: من ألغى
--  قاعةً لا تبقى صورتُها رأسَ خطّته.
--
--  ── وما يُعاد حين لا صورة ─────────────────────────────────────────────────
--
--  `null` — لا نصٌّ فارغ. ومن لم يحجز بعدُ، ومن حجز خدمةً بلا صور، يرى
--  الرأسَ بلا صورةٍ كما كان. **ولا تسقط شاشةٌ لنقص صورة.**
-- ============================================================================

begin;

create or replace function public.api_plan_cover(p_plan_id uuid)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select m.path
    from public.bookings b
    join public.wedding_plans pl on pl.id = b.plan_id
    join public.service_media m on m.service_id = b.service_id
   where b.plan_id = p_plan_id
     -- **الحرزُ سطرٌ واحد**: خطّةُ صاحب الجلسة أو لا شيء. ولا يُوثق بمعرّفٍ
     -- يُمرَّر من التطبيق — ومن مرّر خطّةَ غيره لم يُخرج صورة.
     and pl.user_id = public.current_app_user()
     and b.status not in ('cancelled', 'rejected')
     and m.kind = 'image'
   -- الأقدمُ حجزاً، ثمّ أوّلُ صورةٍ بترتيب صاحبها — وهو ترتيبُ الغلاف نفسُه
   -- في `v_services`.
   order by b.created_at, b.id, m.sort_order, m.created_at
   limit 1
$$;

comment on function public.api_plan_cover(uuid) is
  'مسارُ غلافِ أوّل خدمةٍ حُجزت في خطّة صاحب الجلسة، أو NULL.';

revoke all on function public.api_plan_cover(uuid) from public, anon;
grant execute on function public.api_plan_cover(uuid) to authenticated;

commit;

notify pgrst, 'reload schema';

