-- ============================================================================
--  حذف أقسام الخدمات
--
--  الاستخدام: Supabase ← SQL Editor ← New query ← الصق ← Run.
--  ⚠️ لا رجعة فيه، واقرأ التحذير قبل التشغيل.
--
--  ────────────────────────────────────────────────────────────────────────────
--  ⚠️ الأقسام ليست بيانات عرض
--
--  هي مرجعٌ يقرأه التطبيقان: مقدّم الخدمة يختار قسمه حين يسجّل، والعميل
--  يتصفّح بها. فإذا خلا الجدول:
--    · لا يستطيع مقدّم خدمةٍ جديد أن يكمل تسجيله — لا قسم يختاره
--    · تظهر شاشة التصفّح في تطبيق العميل فارغة
--    · «الحقول الخاصة بالقسم» (السعة، عدد الأشخاص، نوع الفرقة…) تزول معها،
--      فهي مخزَّنةٌ في `custom_fields` داخل صفّ القسم نفسه لا في جدولٍ آخر
--
--  فلا تشغّل هذا إلا وأنت عازمٌ على كتابة أقسامك بنفسك بعده — من صفحة
--  «الأقسام والخدمات» في اللوحة، أو بجُمَل `insert` هنا.
--
--  ────────────────────────────────────────────────────────────────────────────
--  لماذا تُحذف الخدمات المعروضة أوّلاً؟
--
--  `provider_services.category_id` مربوطٌ بـ `on delete restrict` — أي أن
--  القاعدة **ترفض** حذف قسمٍ تحته خدمة، ولا تسقطها معه. وهذا مقصودٌ في
--  المخطط: خدمةٌ بلا قسمٍ لا معنى لها، فمنعُ الحذف خيرٌ من صمتٍ يترك
--  بياناتٍ معطوبة. فتُحذف الخدمات أوّلاً صراحةً.
--
--  أما `provider_categories` فـ `cascade` تسقط وحدها،
--  و`bookings.category_id` و`promotions.category_id` فـ `set null` —
--  يحتفظ الحجز باسم القسم في `category_name` نصّاً، فلا يضيع تاريخه.
-- ============================================================================

-- ────────────────────────────────────────────────────────────────────────────
-- ١. قبل
-- ────────────────────────────────────────────────────────────────────────────
select 'قبل الحذف' as المرحلة,
       (select count(*) from public.service_categories)  as الأقسام,
       (select count(*) from public.provider_services)   as الخدمات,
       (select count(*) from public.provider_categories) as الارتباطات;

-- ────────────────────────────────────────────────────────────────────────────
-- ٢. الحذف
--
--    `where id is not null` ليس حشواً: امتداد `pg-safeupdate` مفعَّلٌ على
--    أدوار Supabase ويرفض `delete` بلا `where` برمز الخطأ 21000.
-- ────────────────────────────────────────────────────────────────────────────
delete from public.provider_services   where id is not null;
delete from public.provider_categories where category_id is not null;
delete from public.service_categories  where id is not null;

-- ────────────────────────────────────────────────────────────────────────────
-- ٣. بعد
-- ────────────────────────────────────────────────────────────────────────────
select 'بعد الحذف' as المرحلة,
       (select count(*) from public.service_categories)  as الأقسام,
       (select count(*) from public.provider_services)   as الخدمات,
       (select count(*) from public.provider_categories) as الارتباطات,
       '—'                                               as ــ,
       (select count(*) from public.governorates)        as المحافظات,
       (select count(*) from public.subscription_plans)  as الباقات,
       (select count(*) from public.admins)              as المسؤولون;
