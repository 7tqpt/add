-- ============================================================================
--  غلافُ الحجز — صورةُ الخدمة المحجوزة في بطاقة «حجوزاتي»
--
--  شغّله بعد `install.sql` و`service_media.sql`. آمنٌ عند التكرار.
-- ============================================================================
--
--  ── ما ينقص اليوم ─────────────────────────────────────────────────────────
--
--  بطاقةُ الحجز نصٌّ كلُّها. واختار صاحبُ المنصّة أن تصير كبطاقة الخطّة:
--  صورةُ الخدمة إلى جانب النصّ.
--
--  و`Booking` في التطبيق لا تحمل غلافَ خدمتها، و`myBookings` تقرأ جدولَ
--  `bookings` وحدَه. والغلافُ في `service_media` — جدولٍ آخر.
--
--  ── ولماذا طريقةٌ لا دالّة ────────────────────────────────────────────────
--
--  في الخطّة كان المطلوبُ **صورةً واحدةً لخطّة**، فدالّةٌ تأخذ معرّفاً
--  وتردّ سطراً. وهنا المطلوبُ **صورةٌ لكلّ حجزٍ في قائمة**، فدالّةٌ لكلّ
--  بطاقةٍ عشرون نداءً على شبكة جوالٍ يمنية. فالطريقةُ تضمّ الغلافَ إلى
--  الصفّ فيأتي معه في نداءٍ واحد — كما يأتي غلافُ الخدمة في `v_services`.
--
--  ── والحرزُ حرزُ الجدول نفسِه ─────────────────────────────────────────────
--
--  `security_invoker = true` — فتُطبَّق سياساتُ `bookings` على القارئ كما
--  تُطبَّق حين يقرأ الجدولَ مباشرةً. **ولا حرزَ جديدٌ يُخترع هنا**: طريقةٌ
--  تتجاوز سياسةَ جدولها بابٌ خلفيّ، ومن قرأ بها قرأ حجوزَ غيره.
--
--  ── وأيُّ صورةٍ ────────────────────────────────────────────────────────────
--
--  أوّلُ صورةٍ بترتيب صاحب الخدمة — وهو ترتيبُ الغلاف نفسُه في `v_services`،
--  فلا تختلف صورةُ الخدمة في «استكشف» عن صورتها في «حجوزاتي».
--
--  و`kind = 'image'` شرطٌ صريح: الجدولُ يحمل الفيديو والصوتَ معها، ومسارُ
--  مقطعٍ لا صورةَ فيه.
-- ============================================================================

begin;

drop view if exists public.v_my_bookings;

create view public.v_my_bookings
with (security_invoker = true) as
select
  b.*,
  (select m.path
     from public.service_media m
    where m.service_id = b.service_id and m.kind = 'image'
    order by m.sort_order, m.created_at
    limit 1) as cover_path
from public.bookings b;

comment on view public.v_my_bookings is
  'حجوزاتُ القارئ كما في الجدول، ومعها غلافُ كلّ خدمة — بحرز `bookings` نفسِه.';

revoke all on public.v_my_bookings from public, anon;
grant select on public.v_my_bookings to authenticated;

commit;

notify pgrst, 'reload schema';

