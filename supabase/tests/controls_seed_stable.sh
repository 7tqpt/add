#!/usr/bin/env bash
# ضوابطُ سالبةٌ لثبات البيانة الأوّليّة.
#
# تكسر كلَّ ضمانةٍ كسراً واحداً وتتأكّد أنّ الحزمةَ تحمرّ. وما لا يسقط
# بالكسر ضمانةٌ كاذبةٌ تُطمئن ولا تحرس.
#
# **وأخطرُ ما يُكسر هنا (أ): يعود المعرّفُ مسحوباً.** وهي الحالُ التي كانت
# طوالَ الوقت: القاعدةُ تُبنى بناءً مختلفاً في كلّ تشغيل، فكلُّ عددٍ يُقاس
# في الحزم الأربع والخمسين يقف على رملٍ — يمرّ عندي ويسقط في CI، ويُظنّ
# العطلُ في الحارس وهو في الأرض.
#
# **وحزمتان لا واحدة.** الضمانةُ موزّعةٌ: الثباتُ في `seed_stable.test.mjs`،
# والعددُ المعلومُ يُسأل عنه أيضاً في `api.test.mjs` — وضابطٌ يشغّل إحداهما
# يمرّ على ما تحرسه الأخرى.
set -uo pipefail
cd "$(dirname "$0")"
command -v node >/dev/null || { echo "لا node في المسار"; exit 1; }

SUITE="seed_stable.test.mjs api.test.mjs"
F=../seed.sql

BACKUP=$(mktemp -d)
cp "$F" "$BACKUP/f"
restore() { cp "$BACKUP/f" "$F"; }
trap 'restore; rm -rf "$BACKUP"' EXIT
PASS=0; FAIL=0

sub() {
  local file="$1" old="$2" new="$3" n
  n=$(python3 - "$file" "$old" <<'PY'
import sys
print(open(sys.argv[1], encoding='utf-8').read().count(sys.argv[2]))
PY
)
  if [ "$n" != "1" ]; then echo "   ✗ المرساةُ تطابق $n مرّة — لا كسرَ وقع"; return 1; fi
  python3 - "$file" "$old" "$new" <<'PY'
import sys
p, old, new = sys.argv[1], sys.argv[2], sys.argv[3]
s = open(p, encoding='utf-8').read()
open(p, 'w', encoding='utf-8').write(s.replace(old, new, 1))
PY
}

run() {
  local name="$1"; shift
  restore
  if ! "$@"; then echo "✗ $name — لم يقع الكسر"; FAIL=$((FAIL+1)); restore; return; fi
  if timeout 600 node --test $SUITE >/dev/null 2>&1; then
    echo "✗ $name — الحزمةُ خضراءُ والضمانةُ مكسورة"; FAIL=$((FAIL+1))
  else
    echo "✓ $name — سقط"; PASS=$((PASS+1))
  fi
  restore
}

echo "== الأساس =="
if timeout 600 node --test $SUITE >/dev/null 2>&1; then echo "أخضر."
else echo "الأساسُ أحمر — لا معنى للضوابط."; exit 1; fi

echo; echo "== الضوابط =="

# ── أ) يعود معرّفُ المستخدم مسحوباً ─────────────────────────────────────────
#
# **وهذا أخطرُها** — وشرحُه في رأس الملفّ. وكلُّ ما بعده يُقسَّم
# بـ`hashtext(u.id)`: من يأخذ خطّةَ عرسٍ، وكم حجزاً يخرج.
run "(أ) معرّفُ المستخدم مسحوب" \
  sub "$F" \
"  md5('app_user:' || i)::uuid," \
"  gen_random_uuid(),"

# ── ب) ومعرّفُ مقدّم الخدمة ─────────────────────────────────────────────────
#
# ومنه: أيُّ قسمٍ يُسند إليه، وأيُّ باقةٍ يشترك فيها، وأله إعلانٌ أم لا.
run "(ب) معرّفُ مقدّم الخدمة مسحوب" \
  sub "$F" \
"  md5('provider:' || i)::uuid," \
"  gen_random_uuid(),"

# ── ج) ومعرّفُ الخدمة يعود يُشتقُّ من مفتاحٍ مسحوب ──────────────────────────
#
# **وهذا أخبثُها.** المعرّفُ «محسوب» في ظاهره — `md5(...)` — لكنّ أحدَ
# مدخلاته (`category_id`) مسحوبٌ هو نفسُه، فيعود السحبُ من بابٍ خلفيّ.
# وقد وقع هذا فعلاً: كتبتُ الاشتقاقَ من `category_id` فبقيت البيانةُ
# تتبدّل، ولم أعرف السببَ حتى قِستُ جدولاً جدولاً.
run "(ج) الاشتقاقُ من مفتاحٍ مسحوب" \
  sub "$F" \
"  md5('service:' || pc.provider_id || ':' || c.slug || ':' || s)::uuid," \
"  md5('service:' || pc.provider_id || ':' || pc.category_id || ':' || s)::uuid,"

# ── د) ومعرّفُ خطّة العرس ───────────────────────────────────────────────────
run "(د) معرّفُ الخطّة مسحوب" \
  sub "$F" \
"  md5('plan:' || u.id)::uuid," \
"  gen_random_uuid(),"

# ── هـ) ومعرّفُ الحجز ───────────────────────────────────────────────────────
#
# ومنه: التقييماتُ والنزاعاتُ والمحادثاتُ وطريقةُ الدفع.
run "(هـ) معرّفُ الحجز مسحوب" \
  sub "$F" \
"  md5('booking:' || pl.id || ':' || n)::uuid," \
"  gen_random_uuid(),"

# ── و) وترقيمُ المراجع يتبع ترتيباً عارضاً ──────────────────────────────────
#
# **ولا يسقط هذا بعدٍّ.** العددُ لا يتغيّر — يتغيّر أيُّ حجزٍ يحمل أيَّ
# مرجع. فما يقيس العددَ وحدَه يمرّ، وبصمةُ المحتوى وحدَها تُسقطه.
#
# **وحذفُ `order by` وحدَه لا يكسر — وقد جرّبتُه فبقيت الحزمةُ خضراء.**
# ولا يعني ذلك أنّ الضمانةَ باطلة: `row_number() over ()` ترقّم بترتيب
# وصولِ الصفوف، و PGlite هنا يمسح بترتيب الإدراج فيتّفق الأمران اتّفاقاً
# لا ضمانة. فالكسرُ المكتوبُ هنا هو **ما يبيحه غيابُ الترتيب**: ترتيبٌ
# عارض. ومن قال «حُذف `order by` ولم تحمرّ فلا بأس» قاس عادةَ المحرّك لا
# عهدَه.
run "(و) المرجعُ يُرقَّم بترتيبٍ عارض" \
  sub "$F" \
"    || lpad(row_number() over (order by pl.id, n)::text, 6, '0')," \
"    || lpad(row_number() over (order by random())::text, 6, '0'),"

# ── ز) و«أوّلُ قسمٍ» يتبع ترتيباً عارضاً ────────────────────────────────────
#
# لمقدّم الخدمة قسمان أحياناً، و`limit 1` بلا `order by` تُسلّم أيَّهما
# اتّفق — فيتبدّل قسمُ الإعلان. والكسرُ هنا كسابقِه: ترتيبٌ عارضٌ مكتوبٌ
# صراحةً، لأنّ الحذفَ المجرّد لا يظهر أثرُه في هذا المحرّك.
run "(ز) قسمُ الإعلان بترتيبٍ عارض" \
  sub "$F" \
"  order by sc.sort_order
  limit 1" \
"  order by random()
  limit 1"

# ── ح) والعددُ المكتوبُ لا يُقاس ────────────────────────────────────────────
#
# ضابطٌ على الحارس نفسِه: لو كُتب في `seed_stable` عددٌ غيرُ ما في القاعدة
# لَوجب أن تحمرّ — وإلّا فالعددُ المكتوبُ زينةٌ لا قياس.
run "(ح) البيانةُ تتغيّر والعددُ المكتوبُ لا" \
  sub "$F" \
"from generate_series(1, 90) as i" \
"from generate_series(1, 88) as i"

echo
echo "الساقط: $PASS — الباقي: $FAIL"
[ "$FAIL" = 0 ]
