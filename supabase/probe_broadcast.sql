-- ============================================================================
--  ⚠️ هذا **يُرسل حملةً حقيقيّة** — لا يقرأ فقط
--
--  حملةٌ جديدةٌ من المحرّر مباشرةً، بنداء `api_admin_broadcast` نفسِها التي
--  تناديها اللوحة. ويصل من تصله إشعارٌ على جواله إن كانت السلسلةُ تعمل.
-- ============================================================================
--
--  ── لماذا هذا، بعد كلّ ما مضى ─────────────────────────────────────────────
--
--  أُغلق كلُّ شيءٍ بالقياس: نصُّ الدوالّ هو نصُّ المستودع (والفرقُ الذي
--  أنذرتُ به كان نهاياتِ أسطرٍ لا منطقاً)، و`broadcast_audience('all')` تُخرج
--  ثلاثةً، وثلاثةُ مستخدمين بأجهزتهم كانوا موجودين وقتَ كلّ حملة، ولا
--  `force row level security`، ونسخةٌ واحدةٌ من كلّ دالّة. و`insertNotification`
--  في اللوحة تكتب «مسوّدة» و`sent_at` فارغاً — فالوسمُ «sent» لا يأتي إلّا
--  من الدالّة. أي أنّها عملت خمسَ مرّاتٍ وأدرجت صفراً في كلّ مرّة.
--
--  **فبقي أن تُنادى من هنا ويُقارن.** وجوابُها يقطع:
--
--    · أعادت **٣** → الدالّةُ سليمةٌ حين أُناديها أنا، والفرقُ في **من
--      ينادي** — أي في صلاحيّات الدور الذي تعمل به اللوحة. وحينئذٍ يصل
--      الثلاثةَ إشعارٌ حقيقيّ، فتُقاس الحلقةُ الأخيرةُ معه.
--    · أعادت **٠** → العلّةُ في الدالّة نفسِها في هذه القاعدة، وأمضي إليها
--      بجملٍ أضيق.
--
--  ── ولماذا سطرُ `set_config` قبلها ────────────────────────────────────────
--
--  `api_admin_broadcast` تسأل `can_write_area('ops')`، وهي تُشتقّ من
--  `auth.uid()`. والمحرّرُ لا جلسةَ فيه، فـ`auth.uid()` فارغةٌ وتُردّ الدالّةُ
--  بـ«لا صلاحية لإرسال الحملات». فيُنتحل أوّلُ مسؤولٍ في `admins` — **لهذه
--  الجلسة وحدَها**، ولا أثرَ لها بعد إغلاق التبويب.
-- ============================================================================

select set_config('request.jwt.claim.sub',
                  (select user_id::text from public.admins
                    where role = 'owner' order by created_at limit 1),
                  false);

with c as (
  insert into public.push_notifications (title, body, audience, status)
  values ('اختبارٌ من المحرّر',
          'إن وصلك هذا على جوالك فالسلسلةُ كلُّها تعمل.',
          'all', 'draft')
  returning id
)
select public.api_admin_broadcast((select id from c)) as "عددُ الصناديق التي وصلتها",
       (select count(*) from public.broadcast_audience('all')) as "وما يُخرجه الجمهورُ الآن";
