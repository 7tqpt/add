// قرارٌ واحد: **أقَبِل المُرسِلُ الرمزَ أم ردَّه؟**
//
// ── ولماذا في ملفٍّ وحده ────────────────────────────────────────────────────
//
// كان السطرُ داخلَ `index.ts` بين نداءَي شبكة، فلم يكن يُقاس. **وكان خاطئاً
// منذ كُتب**: يسأل عن حقلٍ اسمُه `verified`، والمُرسِلُ يُرسل `status`. فكان
// يردّ كلَّ رمزٍ صحيحٍ ويقول لصاحبه «الرمزُ غير صحيح أو انتهت مدّته» — وهو
// يقرأ رمزَه من واتساب ويكتبه حرفاً حرفاً.
//
// وأمسكه سجلُّ الدالّة بعد أن أُضيف إليه سببُ الردّ:
//
//   رُدَّ الرمز: 200 {"status":true,"message":"OTP verified successfully"}
//
// ‏**٢٠٠ و«تم التحقّق بنجاح» — ونحن نردّه.**
//
// وأصلُ الغلط أنّ مثالَ المُرسِل على GitHub يكتب `{ verified: true }` في
// تعليقٍ، وخادمَهم الحيَّ يردّ `status`. فنُسخ التعليقُ ولم يُقس الردُّ.
//
// ‏`.mjs` لا `.ts`: تقرؤه Deno في الدالّة، ويقرؤه Node في الحزمة. ولو بقي
// في `index.ts` لَما بلغه اختبار — ولا Deno في سير التكامل.
//
// ── وما يُقبَل ──────────────────────────────────────────────────────────────
//
// **إشارةٌ موجبةٌ صريحةٌ ولا شيء غيرها.** لا «لم يُردَّ بخطأ» ولا «الجسمُ
// ليس فارغاً»: القبولُ يعني تأكيدَ رقمِ جوالٍ في حساب، فالصمتُ يُقرأ رفضاً.
//
// و`=== true` لا صِدقاً عابراً: `"true"` نصّاً و`1` عدداً يُردّان. فردٌّ
// تبدّل شكلُه يجب أن يُردّ ويُكتب في السجلّ، لا أن يُقرأ قبولاً بالمصادفة.
//
// **والاسمان معاً** — `status` هو ما يردّه الخادمُ الحيّ، و`verified` ما
// يكتبه مثالُهم. فمن بدّل منهما إلى الآخر غداً لم ينكسر شيء.

/// أقَبِل المُرسِلُ الرمز؟
///
/// [httpOk] أكانت حالةُ الردّ ‎2xx‎.
/// [raw] جسمُ الردّ نصّاً كما جاء — **نصّاً لا خريطةً**: ردٌّ ليس JSON يضيع
/// كلُّه بـ`.json()` وحدَها، فلا يبقى ما يُكتب في السجلّ حين يُسأل «لماذا؟».
export function otpVerified(httpOk, raw) {
  if (!httpOk) return false;

  let body;
  try {
    body = JSON.parse(raw);
  } catch {
    // ردٌّ ليس JSON — صفحةُ خطأ من وسيطٍ مثلاً. ولا يُقرأ قبولاً.
    return false;
  }

  if (body === null || typeof body !== 'object') return false;

  return body.verified === true || body.status === true;
}
