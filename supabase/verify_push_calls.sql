-- ============================================================================
--  ماذا ردّت دالّةُ push على كلّ نداء — من القاعدة، بلا فتح سجلّات
--
--  يقرأ ولا يغيّر شيئاً.
-- ============================================================================
--
--  **ولماذا هذا موجودٌ أصلاً:** مُشغِّلُ `push_on_notification` ينادي الدالّةَ
--  بـ`supabase_functions.http_request`، وهي مبنيّةٌ على `pg_net`. و`pg_net`
--  **لا ترمي عطباً عند الفشل** — تضع الطلبَ في طابور، وتكتب الردَّ في
--  `net._http_response`. فالإدراجُ ينجح، والصفُّ يُكتب، والنداءُ يفشل بصمت،
--  ولا شيءَ في القاعدة يقول ذلك... إلّا هذا الجدول.
--
--  وهو الذي يفرّق بين ثلاثٍ يخلطها «لم يصل»:
--
--    · `status_code = 200` → الدالّةُ نجحت، والعلّةُ بعدها: FCM أو الجهاز.
--    · `status_code = 500` → الدالّةُ سقطت، و`content` يقول لماذا حرفاً.
--                            وأرجحُه: «FCM_SERVICE_ACCOUNT غير مضبوط».
--    · لا صفَّ أصلاً       → المُشغِّلُ لم ينادِ، أو `pg_net` غيرُ مفعَّل.
--
--  **والردودُ تُمحى بعد ساعات.** فإن كان الجدولُ فارغاً وقد أرسلتَ أمس،
--  فأرسل حملةً جديدةً ثمّ شغّل هذا فوراً.
--
--  ⚠️ وإن ردّ المحرّرُ «relation net._http_response does not exist» فذلك
--     **جوابٌ لا عطب**: `pg_net` غيرُ مفعَّلة في مشروعك، فالمُشغِّلُ لم يخرج
--     منه نداءٌ واحدٌ قطّ. وتُفعَّل من Database → Extensions → pg_net.
-- ============================================================================

select
  r.id,
  r.status_code                          as "رمز الردّ",
  case
    when r.timed_out                then '⏱️ انتهت المهلة — الدالّةُ لم تردّ في ٥ ثوانٍ'
    when r.error_msg is not null    then '❌ ' || r.error_msg
    when r.status_code = 200        then '✅ الدالّةُ نجحت — والعلّةُ بعدها: FCM أو الجهاز'
    when r.status_code >= 500       then '❌ الدالّةُ سقطت — اقرأ «ما ردّته» أدناه'
    when r.status_code is null      then '⏳ ما زال في الطابور'
    else '⚠️ ردٌّ غيرُ متوقَّع'
  end                                    as الحكم,
  left(coalesce(r.content, ''), 300)     as "ما ردّته",
  r.created                              as الوقت
from net._http_response r
order by r.created desc
limit 15;

-- ----------------------------------------------------------------------------
-- وما زال في الطابور ولم يُنفَّذ بعد
-- ----------------------------------------------------------------------------
select count(*) as "طلباتٌ في الطابور" from net.http_request_queue;
