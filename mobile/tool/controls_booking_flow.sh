#!/usr/bin/env bash
# ضوابطُ سالبةٌ لمسار الحجز: ثلاثُ خطواتٍ ومراجعةٌ قبل الإرسال.
#
# تكسر كلَّ ضمانةٍ كسراً واحداً وتتأكّد أنّ الحزمةَ تحمرّ. وما لا يسقط
# بالكسر ضمانةٌ كاذبةٌ تُطمئن ولا تحرس.
#
# **وكسرٌ يُسقط الحزمةَ بعطبٍ في الترجمة ضابطٌ كاذبٌ كذلك**: يحمرّ لسببٍ غير
# الذي يدّعيه. فكلُّ كسرٍ هنا يُتحقَّق من وقوعه أوّلاً (المرساةُ تطابق مرّةً
# واحدة)، والسطرُ المكسورُ Dart صحيحٌ يُصرَّف.
set -uo pipefail
cd "$(dirname "$0")/.."
command -v flutter >/dev/null || { echo "لا flutter في المسار"; exit 1; }

SUITE="test/booking_flow_test.dart test/coupon_test.dart"
F=lib/src/screens/booking_flow.dart
D=lib/src/screens/service_detail.dart

BACKUP=$(mktemp -d)
cp "$F" "$BACKUP/f"; cp "$D" "$BACKUP/d"
restore() { cp "$BACKUP/f" "$F"; cp "$BACKUP/d" "$D"; }
trap 'restore; rm -rf "$BACKUP"' EXIT
PASS=0; FAIL=0

sub() {
  local file="$1" old="$2" new="$3" n
  n=$(python3 - "$file" "$old" <<'PY'
import sys
print(open(sys.argv[1], encoding='utf-8').read().count(sys.argv[2]))
PY
)
  if [ "$n" != "1" ]; then echo "   ✗ المرساةُ تطابق $n مرّة — لا كسرَ وقع"; return 1; fi
  python3 - "$file" "$old" "$new" <<'PY'
import sys
p, old, new = sys.argv[1], sys.argv[2], sys.argv[3]
s = open(p, encoding='utf-8').read()
open(p, 'w', encoding='utf-8').write(s.replace(old, new, 1))
PY
}

run() {
  local name="$1"; shift
  restore
  if ! "$@"; then echo "✗ $name — لم يقع الكسر"; FAIL=$((FAIL+1)); restore; return; fi
  if timeout 900 flutter test $SUITE >/dev/null 2>&1; then
    echo "✗ $name — الحزمةُ خضراءُ والضمانةُ مكسورة"; FAIL=$((FAIL+1))
  else
    echo "✓ $name — سقط"; PASS=$((PASS+1))
  fi
  restore
}

echo "== الأساس =="
if timeout 900 flutter test $SUITE >/dev/null 2>&1; then echo "أخضر."
else echo "الأساسُ أحمر — لا معنى للضوابط."; exit 1; fi

echo; echo "== الحارسُ بين الخطوات =="

# ── أ) يسقط حارسُ الخطوة الأولى ───────────────────────────────────────────
#
# فيبلغ صاحبُه المراجعةَ بلا عددِ ضيوف، ويصل الخادمَ حجزٌ بصفر.
run "(أ) لا حارسَ على عدد الضيوف" \
  sub "$F" \
"      if (_guestCount <= 0) return tr('اكتب عدد الضيوف رقماً.');" \
"      return null;"

# ── ب) ويسقط حارسُ التاريخ ────────────────────────────────────────────────
#
# **وهذا يُوصل إلى شاشةٍ تقول «لم يُختَر تاريخ»** — فيقرؤها صاحبُها عطباً
# في الشاشة، وهي إنّما تعرض ما لم يملأه.
run "(ب) لا حارسَ على التاريخ" \
  sub "$F" \
"      if (_date == null) return tr('اختر تاريخ العرس.');" \
"      if (false) return tr('اختر تاريخ العرس.');"

# ── ج) ويسقط حارسُ العنوان ───────────────────────────────────────────────
run "(ج) لا حارسَ على العنوان" \
  sub "$F" \
"      if (_address.text.trim().isEmpty) return tr('اكتب عنوان المناسبة.');" \
"      if (_address.text.length > 9999) return tr('اكتب عنوان المناسبة.');"

# ── د) ويُقبل عنوانٌ فراغُه كلُّه ─────────────────────────────────────────
#
# `trim()` هي الفرق: «   » ليست فارغةً حرفاً وهي فارغةٌ معنًى. ومن أرسلها
# أرسل حجزاً بعنوانٍ بياض.
run "(د) عنوانٌ من فراغاتٍ يمرّ" \
  sub "$F" \
"      if (_address.text.trim().isEmpty) return tr('اكتب عنوان المناسبة.');" \
"      if (_address.text.isEmpty) return tr('اكتب عنوان المناسبة.');"

echo; echo "== وما يصل الخادمَ =="

# ── هـ) ويُرسَل عددُ ضيوفٍ ثابتٌ لا ما كُتب ───────────────────────────────
#
# والشاشةُ تعرض ما كتبه، والخادمُ يستقبل غيرَه — وهذا لا تراه عينٌ.
run "(هـ) عددُ الضيوف لا يصل كما كُتب" \
  sub "$F" \
"        guests: _guestCount," \
"        guests: 100,"

# ── (و) كان هنا ضابطٌ للملاحظات، وسقط لأنّه كاذب ─────────────────────────
#
# كسرتُ `notes` فبقيت الحزمةُ خضراء. والعلّةُ ليست في الشاشة: `Booking` في
# `models.dart` **لا تحمل حقلَ ملاحظاتٍ أصلاً**، و`demoCreateBooking` لا
# تستقبله — فالملاحظاتُ تُرسَل إلى `api_create_booking` ولا تعود في النموذج،
# ولا شيءَ في وضع العرض يمكن أن يقيسها.
#
# **فحُذف الضابط**: ضابطٌ لا يسقط يُقرأ ضمانةً وهو فراغ. ويبقى النقصُ
# مكتوباً هنا حتى يُقاس يوماً بحقلٍ في النموذج.

# ── ز) ويُرسَل الكودُ كما كُتب لا كما تحقّق منه الخادم ────────────────────
#
# **وهو أخطرُ ما في الشاشة**: من تحقّق من كودٍ ثمّ بدّله يُرسل كوداً لم يره
# الخادمُ قطّ — فيرى رقماً ويُحاسَب بغيره.
run "(ز) يُرسل نصُّ الحقل بدل الكود المتحقَّق منه" \
  sub "$F" \
"        couponCode: _applied?.code ?? ''," \
"        couponCode: _coupon.text.trim(),"

echo; echo "== والرقمُ المعروض =="

# ── ح) ويُحسب العربونُ على السعر قبل الخصم ───────────────────────────────
#
# فيُعرض «المطلوب الآن» أكبرَ ممّا يطلبه الخادمُ فعلاً.
run "(ح) العربونُ على السعر قبل الخصم" \
  sub "$F" \
"  int get _deposit => (_total * widget.item.depositPercent / 100).round();" \
"  int get _deposit => (widget.item.price * widget.item.depositPercent / 100).round();"

# ── ط) ويُشال قولُ «تقدير» ────────────────────────────────────────────────
#
# **وهذه تنكسر بصمتٍ وهي أخطرُ ما في اللوح.** الأرقامُ تبقى كما هي، والشاشةُ
# تُقرأ وعداً نهائيّاً — فإن حسب الخادمُ غيرَه عند الفاتورة قيل «كذبت عليّ».
run "(ط) لا يُقال إنّ الرقمَ تقدير" \
  sub "$F" \
"            Muted(tr('تقديرٌ — والمبلغ النهائي يحسبه النظام عند تأكيد الحجز.'), size: 11)," \
"            const SizedBox.shrink(),"

echo; echo "== والمراجعةُ تُقرأ ولا يُكتب فيها =="

# ── ي) ويدخل حقلُ كتابةٍ شاشةَ المراجعة ──────────────────────────────────
#
# وشاشةٌ تُراجَع فيها البياناتُ ويُعدَّل فيها في آنٍ تُخفي أيَّ الرقمين
# هو الذي سيُرسل.
run "(ي) حقلُ كتابةٍ في شاشة المراجعة" \
  sub "$F" \
"            KeyValue(tr('العربون الآن'), formatMoney(_deposit))," \
"            TextField(decoration: InputDecoration(labelText: tr('العربون الآن'))),"

# ── ل) ويُنشأ الحجزُ ببلوغ المراجعة لا بتأكيدها ──────────────────────────
#
# **وهذا يُحجز لمن جاء يقرأ ثمّ يعدل**: الشاشةُ تعرض المراجعةَ كما هي،
# والصفُّ قد كُتب في الخادم — فمن ضغط «رجوع» ليبدّل شيئاً وجد حجزاً قائماً
# لا يعلم به. ولا تراه عينٌ في الشاشة.
run "(ل) الحجزُ يُنشأ ببلوغ المراجعة" \
  sub "$F" \
"    setState(() {
      _error = null;
      _step++;
    });" \
"    setState(() {
      _error = null;
      _step++;
    });
    if (_step == 2) _book();"

echo; echo "== وبابُ المسار من صفحة الخدمة =="

# ── ك) ويُشال الزرُّ الذي يفتح المسار ─────────────────────────────────────
#
# فيبقى المسارُ مبنيّاً ولا طريقَ إليه — ميزةٌ كاملةٌ ميتة.
run "(ك) لا زرَّ يفتح المسار" \
  sub "$D" \
"                  child: Text(tr('ابدأ الحجز'))," \
"                  child: Text(tr('راسل مقدّم الخدمة')),"

echo
echo "الساقط: $PASS — الباقي: $FAIL"
[ "$FAIL" = 0 ]
