// قفلُ التطبيق: رمزٌ رباعيٌّ يُطلب بعد غيابٍ طويل.
//
// ── ما هو، وما ليس هو ───────────────────────────────────────────────────────
//
// **وهو قفلُ خصوصيّةٍ لا حصنُ أمان، ويُقال ذلك صراحةً.** أربعةُ أرقامٍ عشرةُ
// آلاف احتمالٍ لا غير. فمن أخذ الجهازَ ومعه وقتٌ يجرّبها كلَّها. وما يمنعه
// هنا شيئان: عدُّ المحاولات، وإخراجُ الحساب بعد خمسٍ خاطئة — فيصير الطريقُ
// الوحيدُ بريداً وكلمةَ مرور.
//
// وما يحميه فعلاً: أن يفتح أخوك جوالك فيرى حجوزاتك ومحادثاتك ومبالغك.
//
// ── أربعةُ قراراتٍ تستحقّ أن تُقرأ ──────────────────────────────────────────
//
// **١) الرمزُ لا يُخزَّن، بل تُخزَّن بصمتُه.** SHA-256 على الرمز مع مِلحٍ
// عشوائيٍّ لكلّ جهاز. فمن قرأ الخزنة لم يجد «1234» بل بصمةً لا تُعكس.
//
// **٢) وفي خزنة النظام لا في ملفٍّ عاديّ** — Keychain في آيفون وKeystore في
// أندرويد. و`shared_preferences` تكفي للتفضيلات ولا تصلح لسرّ.
//
// **٣) ولا بدّ من مخرجٍ لمن نسي.** ولولاه لَحُبس صاحبُ الحساب عن حجوزاته
// ومحادثاته إلى الأبد، وهو أذىً أكبرُ من الذي يمنعه القفل. والمخرجُ خروجٌ
// ودخولٌ بالبريد وكلمة المرور — يعرفهما صاحبُ الحساب وحده.
//
// **٤) والقفلُ كان اختياريّاً، وصار مفروضاً — والقرارُ نُقض بعلمٍ لا سهواً.**
//
// كان مكتوباً هنا: «من لم يشغّله لا يراه أبداً — وقفلٌ يُفرض على من لا يريده
// عائقٌ يوميٌّ لا حماية». ثمّ طلب صاحبُ المنصّة أن يُفرض على العميل ومقدّم
// الخدمة جميعاً، وعُرضت عليه الصورةُ وثمنُها — **كلُّ فتحةٍ تُطالب برمزٍ أو
// بصمة** — فاختار: يُفرض فورَ الدخول، ولا يُطفأ من الإعدادات بعدها.
//
// والبابُ `LockGateScreen` في `lock.dart`، ويضعه `root.dart` مكانَ التطبيق
// لمن لا قفلَ له. وحُجّةُ الاختياريّة أعلاه تبقى مكتوبةً لا تُمحى: من أراد
// ردَّ القرار يوماً يجد ما قيل فيه أوّلَ مرّة.
library;

import 'dart:convert';
import 'dart:math';

import 'package:crypto/crypto.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';

import 'biometrics.dart';
import 'i18n.dart';

// **ولا مهلةَ تُختار بعد اليوم — يُقفل فورَ المغادرة.**
//
// كانت خمسةُ خيارات: فوراً، وبعد دقيقة، وخمسٍ، وربعِ ساعة، وساعة. وحُذفت،
// وحُذف معها حسابُ لحظةِ المغادرة وحفظُها في الخزنة.
//
// **وعلّةُ الحذف أنّ الخيار كان يُضعف القفلَ بيد صاحبه وهو لا يدري.** من
// وضع رمزاً إنّما وضعه ليمنع من يمسك جوالَه أن يقرأ حجوزاته؛ و«بعد ربع
// ساعة» — وكانت هي الافتراضيّة — تعني أنّ من أخذ الجوالَ من يده يفتح كلَّ
// شيءٍ ما لم تمضِ خمسَ عشرةَ دقيقة. وهي الحالُ الغالبة: الجوالُ يُؤخذ
// ويُنظَر فيه ويُعاد في دقيقة.
//
// وخمسةُ أزرارٍ تسأل صاحبَها سؤالاً أمنيّاً لا يملك جوابَه — والجوابُ
// الصحيحُ واحدٌ منها فقط.
//
// ── وهنا كُتب: «وثمنُه معلومٌ ومقبول» — **وكان خطأً، وأثبته الاستعمال** ──
//
// كان نصُّ ما كُتب: «من فتح ورقةَ المشاركة أو معرضَ الصور ثمّ عاد يُطالَب
// برمزه، لأنّ التطبيق غادر المقدّمةَ فعلاً. وهذا ما تفعله تطبيقاتُ البنوك،
// وهو ثمنُ القفل لا عطبٌ فيه». **ويُترك مكتوباً لأنّه كان الحجّة.**
//
// وردَّ عليه صاحبُ المنصّة بما رآه: «عند ما أجي أغيّر صورة يخرجني التطبيق
// ولم يتغيّر شيء». **ولم يكن الثمنُ ما ظُنّ.** ثمنان لا واحد:
//
//   ١) شاشةُ الرمز في وجهه وهو لم يغادر — وهو ما احتُسب.
//   ٢) **وضياعُ عمله، وهو ما لم يُحتسب**: `RootScreen` يبدّل الشجرةَ كلَّها
//      بشاشة الرمز، فتُهدَم الشاشةُ المنتظِرةُ للصورة، ويرجع انتظارُها إلى
//      حالةٍ `mounted == false` فيخرج صامتاً قبل أن يرفع. فلا الصورةُ
//      تبدّلت ولا قيل له لماذا.
//
// **وتطبيقاتُ البنوك لا تفعل هذا**: تعرف رحلتَها من غياب صاحبها. والقياسُ
// عليها كان في غير محلّه.
//
// **فصار الحكمُ:** العودةُ من نافذةٍ فتحها التطبيقُ نفسُه ليست غياباً —
// انظر `beginExcursion`. وما عداها يُقفل فوراً كما كان، ولم يُمسَّ منه شيء.

/// مهلةُ الرحلة التي يفتحها التطبيقُ بنفسه — **وحدُّها اختيارُ صاحب المنصّة**.
///
/// عُرضت عليه ثلاثةُ حلولٍ للعطل، فاختار الإعفاءَ **بحدٍّ زمنيّ**: من ترك
/// المعرضَ مفتوحاً وذهب لا يعود إلى حسابٍ مفتوح.
///
/// **ودقيقتان لا خمسٌ ولا عشر:** انتقاءُ صورةٍ من المعرض عملُ ثوانٍ، وما
/// طال عنه فصاحبُه في شيءٍ آخر.
const lockExcursionGrace = Duration(minutes: 2);

/// عددُ المحاولات الخاطئة قبل إخراج الحساب.
///
/// **وخمسٌ لا ثلاث:** الرمزُ يُدخَل بإبهامٍ على شاشةٍ صغيرة، والخطأُ في
/// الإدخال وارد. وثلاثٌ تُخرج صاحبَ الحساب لأنّه أخطأ الضغط.
const lockMaxAttempts = 5;

const _keyHash = 'lock_pin_hash';
const _keySalt = 'lock_pin_salt';

/// **أشغّل صاحبُ الجهاز البصمةَ لهذا القفل؟**
///
/// وهو تفضيلٌ لا سرّ — لكنّه يسكن الخزنةَ نفسَها: لو سكن
/// `shared_preferences` لَأمكن إطفاؤه من خارج التطبيق على جهازٍ مكسور،
/// ولا فائدةَ من خزنةٍ للرمز ومِلفٍّ عاديٍّ لمن يفتحه.
const _keyBiometric = 'lock_biometric';
// **ويُمسح مفتاحا العهد القديم عند الإزالة.** «lock_after» و«lock_left_at»
// لم يعودا يُقرآن، لكنّهما باقيان في خزائن الأجهزة التي حدّثت. ومفتاحٌ
// مهجورٌ في الخزنة لا يضرّ اليوم، لكنّه يضرّ يومَ يُكتب مفتاحٌ باسمٍ يشبهه.
const _keyLegacyAfter = 'lock_after';
const _keyLegacyLeftAt = 'lock_left_at';

/// بديلٌ يُركَّب في الاختبارات — لا خزنةَ نظامٍ في `flutter test`.
///
/// **ولولاه لَما قِيس شيءٌ من هذا الملفّ**: خزنةُ النظام شيفرةٌ أصليّة لا
/// وجودَ لها في بيئة الاختبار، فكلُّ نداءٍ يرمي.
Map<String, String>? lockStorageOverride;

/// الساعةُ التي تُقاس بها مهلةُ الرحلة — تُبدَّل في الاختبار.
///
/// **ولولاها لَبقيت المهلةُ بلا حارس.** قياسُها بالانتظار الحقيقيّ يعني
/// حزمةً تقف دقيقتين، فلا تُكتب أصلاً — فيصير الحدُّ الذي اختاره صاحبُ
/// المنصّة رقماً لا يقيسه شيء. و`fakeAsync` لا يحرّك `DateTime.now`.
DateTime Function() lockClock = DateTime.now;

Future<String?> _read(String key) async {
  final fake = lockStorageOverride;
  if (fake != null) return fake[key];
  try {
    return await const FlutterSecureStorage().read(key: key);
  } catch (_) {
    return null;
  }
}

Future<void> _write(String key, String? value) async {
  final fake = lockStorageOverride;
  if (fake != null) {
    if (value == null) {
      fake.remove(key);
    } else {
      fake[key] = value;
    }
    return;
  }
  try {
    if (value == null) {
      await const FlutterSecureStorage().delete(key: key);
    } else {
      await const FlutterSecureStorage().write(key: key, value: value);
    }
  } catch (_) {
    // خزنةٌ لا تُكتب: القفلُ لا يُفعَّل، والتطبيق يعمل. ولا يُسقَط شيء.
  }
}

String _digest(String pin, String salt) => sha256.convert(utf8.encode('$salt:$pin')).toString();

String _newSalt() {
  final random = Random.secure();
  return base64Url.encode(List<int>.generate(16, (_) => random.nextInt(256)));
}

/// أرمزٌ مضبوطٌ على هذا الجهاز؟
Future<bool> lockIsSet() async => (await _read(_keyHash)) != null;

/// يضبط الرمز — أربعةُ أرقامٍ لا غير.
///
/// **ويُردّ ما ليس أربعةَ أرقام** هنا لا في الشاشة وحدها: الشاشةُ تُبدَّل
/// وهذا يبقى.
Future<void> lockSetPin(String pin) async {
  if (!RegExp(r'^\d{4}$').hasMatch(pin)) {
    throw tr('الرمز أربعة أرقام.');
  }
  final salt = _newSalt();
  await _write(_keySalt, salt);
  await _write(_keyHash, _digest(pin, salt));
}

/// يزيل القفل — **والبصمةُ تسقط معه**.
///
/// ولولا ذلك لَبقي تفضيلُ البصمة قائماً لقفلٍ لا وجودَ له، فيعود من فعّل
/// القفلَ بعد شهرٍ فيجد بصمةً يُسأل عنها ولم يطلبها اليوم.
Future<void> lockClear() async {
  await _write(_keyHash, null);
  await _write(_keySalt, null);
  await _write(_keyBiometric, null);
  await _write(_keyLegacyAfter, null);
  await _write(_keyLegacyLeftAt, null);
}

/// أشُغِّلت البصمةُ لهذا القفل على هذا الجهاز؟
Future<bool> lockBiometricIsOn() async => (await _read(_keyBiometric)) == '1';

/// يشغّل البصمةَ أو يطفئها — **ولا تُشغَّل بلا رمزٍ مضبوط**.
///
/// القفلُ واحدٌ والبابان يفتحانه، فبصمةٌ بلا رمزٍ تحتها قفلٌ لا مخرجَ منه
/// إن أخفق الحسّاس.
Future<void> lockSetBiometric(bool on) async {
  if (on && !await lockIsSet()) throw tr('فعّل قفل التطبيق أولاً.');
  await _write(_keyBiometric, on ? '1' : null);
}

/// أيطابق هذا الرمزُ المضبوط؟
Future<bool> lockVerify(String pin) async {
  final hash = await _read(_keyHash);
  final salt = await _read(_keySalt);
  if (hash == null || salt == null) return false;
  return _digest(pin, salt) == hash;
}

/// النسخةُ الواحدة — كما `appLocale` في `i18n.dart`.
///
/// **ونسخةٌ واحدةٌ لا تمريرٌ عبر أربع شاشات.** القفلُ حالُ التطبيق كلِّه، لا
/// حالُ شاشة. وتمريرُه من الجذر إلى الإعدادات يمرّ بالقشرة وبطاقة الحساب
/// وليس لهما به شأن.
final appLock = AppLock();

/// يُنفَّذ عملٌ يفتح **نافذةَ نظامٍ خارج التطبيق** — فلا تُعدُّ العودةُ منه
/// غياباً يُوجب الرمز. انظر `AppLock.beginExcursion`.
///
/// **وموضعٌ واحدٌ لا سبعة.** المعرضُ والكاميرا والملفّاتُ وواتساب وإعداداتُ
/// النظام والخرائط كلُّها تمرّ من هنا — ولو لُفَّ كلُّ موضعٍ بيده لَنُسي
/// الثامنُ يوم يُكتب، فيُخرج صاحبَه من حيث لا يُدرى.
///
/// **و`finally` لا `then`:** رحلةٌ تسقط بخطأ يجب أن تنتهي كما تنتهي الناجحة،
/// وإلّا بقي القفلُ معطَّلاً إلى أن تنقضي مهلتُه.
Future<T> awayFromApp<T>(Future<T> Function() body) async {
  appLock.beginExcursion();
  try {
    return await body();
  } finally {
    appLock.endExcursion();
  }
}

/// حارسُ القفل: يعرف متى غاب صاحبُه ومتى يُطلب الرمز.
///
/// **والزمنُ يُقاس عند المغادرة لا عند العودة.** التطبيق قد يُقتل في الخلفيّة
/// فلا يعمل مؤقّتٌ فيه — والذي يبقى هو **لحظةُ آخر استعمال**، تُقارَن بالساعة
/// عند العودة.
class AppLock extends ChangeNotifier {
  bool _enabled = false;
  bool _locked = false;

  /// أغادر التطبيقُ المقدّمةَ منذ آخر فتح؟
  ///
  /// **وعلامةٌ لا لحظةُ زمن.** لم يبقَ ما يُحسب: الغيابُ غيابٌ مهما قصر.
  /// وهي تمنع أن يُقفل التطبيقُ على `resumed` جاءت بلا `paused` قبلها —
  /// وهي تقع في بعض الأجهزة.
  bool _left = false;
  int _wrong = 0;
  bool _biometric = false;

  bool get enabled => _enabled;
  bool get locked => _enabled && _locked;
  int get wrongAttempts => _wrong;
  int get attemptsLeft => lockMaxAttempts - _wrong;

  /// أشُغِّلت البصمةُ لهذا القفل؟ — **ولا معنى لها بلا قفل**.
  bool get biometricEnabled => _enabled && _biometric;

  /// يُقرأ عند الإقلاع — **وكلُّ إقلاعٍ مقفل**.
  ///
  /// وهو أصدقُ ما يمكن قولُه: التطبيقُ كان مغلقاً، ولا يُعرف كم مضى ولا في
  /// يد من كان الجوال.
  Future<void> boot() async {
    _enabled = await lockIsSet();
    _biometric = _enabled && await lockBiometricIsOn();
    _locked = _enabled;
    _left = false;
    notifyListeners();
  }

  /// يُنادى حين يغادر التطبيقُ المقدّمة.
  ///
  /// ولا يُقفل هنا: القفلُ عند العودة، وإلّا لَرأى صاحبُه شاشةَ الرمز تُرسم
  /// خلفه وهو يغادر.
  void onLeave() {
    if (!_enabled) return;
    _left = true;
  }

  /// يُنادى عند العودة — فيُقفل إن كان غادر.
  void onReturn() {
    if (!_enabled || _locked || !_left) return;
    // **ورحلةٌ فتحها التطبيقُ بنفسه ليست غياباً.** انظر `beginExcursion`.
    if (_inExcursion()) {
      _left = false;
      return;
    }
    _locked = true;
    _left = false;
    notifyListeners();
  }

  // ── رحلةٌ خارج التطبيق يفتحها التطبيقُ نفسُه ──────────────────────────────
  //
  // **وهذا عطلٌ شُكي منه لا تحسينٌ مقترح.** قال صاحبُ المنصّة: «عند ما أجي
  // أغيّر صورة يخرجني التطبيق ولم يتغيّر شيء». والمعرضُ نافذةُ نظامٍ خارج
  // التطبيق: يهبط التطبيقُ إلى الخلفيّة فيُسجَّل غياباً، ويعود فيُقفل —
  // فيبدّل `RootScreen` الشجرةَ كلَّها بشاشة الرمز، **وتُهدَم معها الشاشةُ
  // المنتظِرةُ للصورة**، فيرجع انتظارُها صامتاً قبل أن يرفع شيئاً. فأثران
  // لسببٍ واحد: شاشةُ رمزٍ في وجهه، وصورةٌ لم تتبدّل.
  //
  // **وليس المعرضَ وحدَه:** الكاميرا، وانتقاءُ الملفّات، وواتساب، وإعداداتُ
  // النظام، والخرائط — كلُّها تفعلها.
  //
  // **والحدُّ الزمنيُّ اختيارُ صاحب المنصّة** من ثلاثةٍ عُرضت عليه: يُعفى
  // العائدُ من نافذةٍ فتحها التطبيق، **ما لم تطُل الرحلةُ فوق دقيقتين**. فمن
  // ترك المعرضَ مفتوحاً وذهب لا يعود إلى حسابٍ مفتوح.
  //
  // **وعدٌّ لا رايةٌ واحدة:** تُفتح ورقةٌ فيها منتقيان، أو يُنادى منتقٍ وهو
  // مفتوح — فرايةٌ واحدةٌ يُطفئها الأوّلُ وينكشف الثاني.

  int _excursions = 0;
  DateTime? _excursionAt;

  /// أنحن في رحلةٍ فتحها التطبيق، ولمّا تطُل؟
  ///
  /// **والمهلةُ وحدَها تحكم، ولا تُمحى الرحلةُ هنا.** جرّبتُ محوَها عند
  /// انقضاء المهلة وكتبتُ له ضابطاً سالباً — **فلم يسقط**: المحوُ لا يغيّر
  /// شيئاً يُرى، لأنّ `_excursionAt` لا يتقدّم، فما انقضى يبقى منقضياً في
  /// كلّ سؤالٍ بعده. فحُذف السطران ولم يُدَّعَ لهما حرز.
  ///
  /// **لكنّ محاولةَ كسرهما كشفت عيباً حقيقيّاً بجوارهما** — في
  /// `beginExcursion`، لا هنا.
  bool _inExcursion() {
    if (_excursions == 0) return false;
    final at = _excursionAt;
    return at != null && lockClock().difference(at) <= lockExcursionGrace;
  }

  /// كم رحلةً مفتوحةً الآن — **يُقرأ ليُقاس ولتُنظَّف النسخةُ الواحدة**.
  ///
  /// `awayFromApp` تعمل على `appLock` العامّ، فرحلةٌ يتركها اختبارٌ مفتوحةً
  /// تُعفي الذي بعده فيمرّ على قفلٍ لا يقفل.
  int get excursionsOpen => _excursions;

  /// يبدأ رحلةً: نافذةُ نظامٍ يفتحها التطبيق (معرضٌ أو كاميرا أو ملفّاتٌ أو
  /// تطبيقٌ آخر).
  /// **ورحلةٌ مهجورةٌ لا تسمّم التي بعدها.** كان هذا `_excursionAt ??=
  /// lockClock()` — فلو بقيت رحلةٌ مفتوحةً من قبل (تُهدَم الشاشةُ قبل أن
  /// تُنهيَها، أو يسقط العملُ قبل أن يفتح النافذة) ومضت مهلتُها، لَورثت
  /// **الرحلةُ الجديدةُ لحظةَ بدء القديمة** فوُلدت منقضيةً — فيعود العطلُ
  /// بعينه: يفتح معرضَه فيُلقى على شاشة الرمز.
  ///
  /// وكُشف هذا بضابطٍ سالبٍ **لم يسقط**، لا بقراءةٍ عابرة.
  void beginExcursion() {
    final at = _excursionAt;
    if (at == null || lockClock().difference(at) > lockExcursionGrace) {
      // ما مضى مهجورٌ لا يُحتسب: تبدأ الرحلةُ من الآن ووحدَها.
      _excursions = 0;
      _excursionAt = lockClock();
    }
    _excursions++;
  }

  /// ينهيها. **ويُنادى في `finally` أبداً** — رحلةٌ لا تنتهي تُعطّل القفل
  /// إلى أن تنقضي مهلتُها.
  void endExcursion() {
    if (_excursions > 0) _excursions--;
    if (_excursions == 0) _excursionAt = null;
  }

  /// أهذا هو الرمزُ الحاليّ؟ — سؤالٌ بلا فتحٍ ولا عدّ.
  ///
  /// **ولا تُعدّ محاولةً خاطئة، ولا تفتح قفلاً.** تُستعمل قبل تبديل الرمز،
  /// والتطبيقُ حينها مفتوحٌ بيد صاحبه. ولو مرّت على `unlock` لَأخرجت حسابَ
  /// من أخطأ خمساً وهو يبدّل رمزَه في إعداداته.
  Future<bool> verify(String pin) => lockVerify(pin);

  /// يفتح بالرمز، أو يعدّ محاولةً خاطئة.
  ///
  /// ويعيد `true` إن فُتح. ومن بلغ الحدَّ يُخرَج حسابُه — والمنادي هو من
  /// يُخرجه، فالخروجُ شأنُ الجلسة لا شأنُ القفل.
  Future<bool> unlock(String pin) async {
    if (await lockVerify(pin)) {
      _locked = false;
      _wrong = 0;
      _left = false;
      notifyListeners();
      return true;
    }
    _wrong++;
    notifyListeners();
    return false;
  }

  /// يفتح بالبصمة — ويعيد `true` إن طابقت.
  ///
  /// **ولا تُعدّ محاولةً خاطئة.** عدُّ المحاولات في `unlock` حرزٌ من تجريب
  /// عشرةِ آلاف رمز، والبصمةُ لا تُجرَّب: من وضع إصبعاً لا يملكه لم يقترب
  /// من الرمز شيئاً. ولو عُدَّت لَأخرجت حسابَ من أخفق حسّاسُه خمسَ مرّاتٍ
  /// وهو صاحبُه.
  Future<bool> unlockWithBiometrics() async {
    if (!biometricEnabled) return false;
    if (!await biometrics.authenticate()) return false;
    _locked = false;
    _wrong = 0;
    _left = false;
    notifyListeners();
    return true;
  }

  /// يشغّل البصمةَ أو يطفئها — ويعيد الحالَ بعد الكتابة.
  Future<void> setBiometric(bool on) async {
    await lockSetBiometric(on);
    _biometric = on;
    notifyListeners();
  }

  bool get exhausted => _wrong >= lockMaxAttempts;

  /// يفعّل القفل بالرمز — **ولا يُقفل عليه في اللحظة نفسِها**.
  ///
  /// من ضبط رمزَه للتوّ لم يغادر بعد، وشاشةُ رمزٍ تُلقى في وجهه فورَ الضبط
  /// تُقرأ عطباً لا حمايةً.
  Future<void> enable(String pin) async {
    await lockSetPin(pin);
    _enabled = true;
    // **ولا تُشغَّل البصمةُ بلا طلب.** من فعّل القفلَ اختار رمزاً، ولم
    // يختر بعدُ أن يفتحه بإصبعه.
    _biometric = false;
    _locked = false;
    _left = false;
    _wrong = 0;
    notifyListeners();
  }

  Future<void> disable() async {
    await lockClear();
    _enabled = false;
    _locked = false;
    _wrong = 0;
    // **والبصمةُ تسقط في الذاكرة كما سقطت في الخزنة** — ولولا هذا السطر
    // لَبقيت الرايةُ مرفوعةً حتى الإقلاع التالي.
    _biometric = false;
    notifyListeners();
  }

  /// يُنادى بعد الخروج: القفلُ يُزال مع الحساب.
  ///
  /// **ولولا هذا لَبقي رمزُ من خرج قائماً**، فيدخل صاحبٌ آخرُ بحسابه على
  /// الجهاز نفسه فيجد رمزاً لا يعرفه ولا سبيلَ له إليه.
  Future<void> forget() => disable();
}
