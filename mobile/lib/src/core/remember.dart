/// «تذكّرني»: أتبقى الجلسةُ بعد إغلاق التطبيق؟
///
/// ── ولماذا كُتب هذا أصلاً ───────────────────────────────────────────────────
///
/// أرسل صاحبُ المنصّة تصميماً فيه مربّعُ «تذكّرني»، وقيل له إنّ الجلسةَ
/// محفوظةٌ أبداً في كلّ حال — **فمربّعٌ يُرفع ويُخفض ولا يقع شيء كذبٌ في
/// شاشة**. فاختار الصورةَ كما هي، فصار للمربّع معنىً واحدٌ صادق:
///
///   **من خفضه خرج من حسابه عند أوّل فتحةٍ بعد إغلاق التطبيق.**
///
/// ── وأين يقع الخروج ────────────────────────────────────────────────────────
///
/// في `Session.boot()` وحدَه — أي عند **الإقلاع البارد** لا عند كلّ عودةٍ من
/// الخلفيّة. ومن غادر التطبيقَ دقيقةً ثمّ عاد لا يجد نفسه مطروداً، وهو ما
/// يفهمه الناسُ من «إغلاق التطبيق».
///
/// ── ولا تُمحى الرايةُ بعد استعمالها ────────────────────────────────────────
///
/// هي **آخرُ اختيارٍ لصاحب الجهاز** لا أمرٌ يُنفَّذ مرّةً: من دخل ومربّعُه
/// مخفوضٌ يريد ذلك في كلّ مرّة، لا في المرّة الأولى وحدَها. ويُرفع بالدخول
/// ومربّعُه مرفوع.
///
/// **والافتراضُ «نعم»** — فمن لم يمرّ على هذه الشاشة قطُّ (وكلُّ من في
/// الأجهزة اليوم كذلك) لا يتبدّل عليه شيء.
library;

import 'package:flutter_secure_storage/flutter_secure_storage.dart';

const _key = 'auth_remember';

/// بديلٌ يُركَّب في الاختبارات — **لا خزنةَ نظامٍ في `flutter test`**.
///
/// وهو نظيرُ `lockStorageOverride`: الخزنةُ شيفرةٌ أصليّةٌ لا وجودَ لها في
/// بيئة الاختبار، فكلُّ نداءٍ يرمي.
Map<String, String>? rememberStorageOverride;

/// أتبقى الجلسةُ بعد إغلاق التطبيق؟ — و**الافتراضُ نعم**.
Future<bool> rememberIsOn() async {
  final fake = rememberStorageOverride;
  if (fake != null) return fake[_key] != '0';
  try {
    return (await const FlutterSecureStorage().read(key: _key)) != '0';
  } catch (_) {
    // خزنةٌ لا تُقرأ: يُبقى على الافتراض، ولا يُطرد أحدٌ من حسابه لأنّ
    // قراءةَ تفضيلٍ أخفقت.
    return true;
  }
}

/// يكتب الاختيار.
Future<void> setRemember(bool on) async {
  final fake = rememberStorageOverride;
  if (fake != null) {
    fake[_key] = on ? '1' : '0';
    return;
  }
  try {
    await const FlutterSecureStorage().write(key: _key, value: on ? '1' : '0');
  } catch (_) {
    // خزنةٌ لا تُكتب: التفضيلُ لا يُحفظ، والدخولُ يتمّ. ولا يُسقَط شيء.
  }
}
