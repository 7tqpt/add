// نسخةُ التطبيق المثبَّتة، ومنصّتُه.
//
// ── ولماذا ثابتان لا حزمةُ `package_info_plus` ──────────────────────────────
//
// المعتادُ أن تُقرأ النسخةُ من المنصّة بحزمةٍ أصليّة. وقد كلّفت حزمةٌ أصليّةٌ
// واحدةٌ بناءً ساقطاً قبل ساعة: `flutter_secure_storage` ١١ اشترطت
// `compileSdk 37` والمشروع على ٣٦. **وكلُّ حزمةٍ أصليّةٍ بابُ سقوطٍ في بناءٍ
// لا يُرى في `flutter test`** — ولا Android SDK في بيئة الاختبار أصلاً.
//
// والذي نحتاجه رقمٌ واحدٌ يعرفه المستودعُ نفسُه: `version: 1.0.0+1` في
// `pubspec.yaml`. فيُكتب هنا ثابتاً، **ويحرسه اختبارٌ يقرأ `pubspec.yaml`
// ويقارن**. فلا يفترق الاثنان بمرور الوقت، ولا حزمةَ أصليّةٌ ثالثة.
//
// ولولا ذلك الحارس لكان هذا أسوأَ من الحزمة: رقمٌ يُنسى تحديثُه، فيظنّ
// التطبيق نفسَه قديماً أبداً — أو حديثاً أبداً فلا يُخبر أحداً بشيء.
library;

import 'package:flutter/foundation.dart';

/// رقمُ البناء المثبَّت — الجزءُ الذي بعد `+` في `pubspec.yaml`.
///
/// **وهو المقارَن لا اسمُ النسخة.** «1.0.0» نصٌّ يُقارَن بالحروف فيصير
/// «1.0.10» أقدمَ من «1.0.9»، ورقمُ البناء عددٌ صحيحٌ يزيد أبداً — وعليه
/// قيدُ `unique (platform, build)` في القاعدة.
const appBuild = 139;

/// اسمُ النسخة كما يُعرض للناس — الجزءُ الذي قبل `+`.
const appVersionName = '1.1.1';

/// ما يُعرض لصاحب الجهاز — «الإصدار ١٫٠٫٨ (٩)».
///
/// **وكان مكتوباً بيده في شاشتين: «الإصدار 1.0.0».** فبقي على ١٫٠٫٠ ثماني
/// نسخٍ متتالية، وصاحبُ الجهاز لا يملك أن يعرف أيَّ نسخةٍ يشغّل — ولا نحن.
/// وسُئلنا فعلاً: «عدّلتَ الأيقونات ولم تتغيّر» — ولا سبيلَ إلى الجواب إلّا
/// أن يُعرف أيُّ حزمةٍ في يده.
///
/// **والاسمُ وحده بلا رقم البناء** — «تصفير نسخه خليها 1.1.1 بدون (127)هذا العدد»،
/// واختار صاحبُ المنصّة (أ). فصار الاسمُ ‎1.1.1‎، **ورقمُ البناء باقٍ يزيد في الداخل**
/// (`appBuild`): Android يرفض تثبيتَ حزمةٍ رقمُ بنائها أصغرُ ممّا على الجهاز،
/// والتحديثُ يُقارَن به. فتصفيرُه كان يعني أن يحذف كلُّ مستخدمٍ التطبيقَ ويعيده.
/// ويُطابَق بالإصدار على GitHub بوسم `build-<رقم الجولة>` لا بهذا السطر.
String get appVersionLabel => 'الإصدار $appVersionName';

/// اسمُ المنصّة كما هو في عمود `app_versions.platform`.
///
/// **و`defaultTargetPlatform` لا `Platform.isIOS`:** الثانية من `dart:io`،
/// واستيرادُها يكسر بناءَ الويب — وهذا درسٌ مدفوعٌ في هذا المشروع من قبل.
String get appPlatform => defaultTargetPlatform == TargetPlatform.iOS ? 'ios' : 'android';
