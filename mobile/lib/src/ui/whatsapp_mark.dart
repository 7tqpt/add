// شعارُ واتساب — **الشعارُ نفسُه بلونه الأخضر**، لا رمزُ محادثةٍ يشبهه.
//
// اختاره صاحبُ المنصّة من ثلاث: «(أ) شعار واتساب نفسه بلونه الأخضر»، فيعرف
// صاحبُ الرقم من أوّل نظرةٍ أين يصله الرمز. وكان في صورته بلوننا النبيذيّ،
// والشعارُ بلونٍ غيرِ لونه يُقرأ تقليداً لا إشارة.
//
// ── ومن أين جاء الخطّ ─────────────────────────────────────────────────────
//
// من حزمة **Simple Icons** (`simple-icons@13.21.0`، ملفّ
// `icons/whatsapp.svg`) — ورخصةُ بياناتها **CC0**. ومساره فيه أقواسُ SVG
// (`a`) لا يقرؤها `Path` في Flutter، فحُوّل كلُّ قوسٍ إلى منحنياتٍ مكعّبة
// بـ`svgpathtools` مرّةً واحدة، وكُتبت النتيجةُ أرقاماً هنا — **فلا حزمةَ
// جديدةَ ولا أصلَ صورةٍ في التطبيق**، ويُرسم حادّاً على كلّ مقاس.
//
// والعلامةُ نفسُها لواتساب (Meta)؛ وتُستعمل هنا لتقول «يصلك الرمزُ على
// واتساب» — وهو ما يحدث فعلاً.
import 'package:flutter/material.dart';

/// أخضرُ واتساب.
const whatsappGreen = Color(0xFF25D366);

/// شعارُ واتساب بمقاس [size] ولون [color].
class WhatsAppMark extends StatelessWidget {
  const WhatsAppMark({super.key, this.size = 24, this.color = whatsappGreen});

  final double size;
  final Color color;

  @override
  Widget build(BuildContext context) => SizedBox.square(
    dimension: size,
    child: CustomPaint(painter: _WhatsAppPainter(color)),
  );
}

class _WhatsAppPainter extends CustomPainter {
  const _WhatsAppPainter(this.color);
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / 24, size.height / 24);
    canvas.drawPath(whatsappPath(), Paint()..color = color);
  }

  @override
  bool shouldRepaint(_WhatsAppPainter old) => old.color != color;
}

/// مسارُ الشعار في مربّعٍ ٢٤×٢٤ — كما في `viewBox` أصله.
///
/// **وقاعدةُ الملء `nonZero`** كقاعدة SVG الافتراضيّة: الفقاعةُ حلقةٌ لأنّ
/// مسارها الداخليَّ يدور عكسَ الخارجيّ — ولو صارت `evenOdd` لَما تغيّر
/// شيء هنا، لكنّ الأصلَ يُتّبع.
Path whatsappPath() {
  final path = Path();
  var i = 0;
  while (i < _ops.length) {
    switch (_ops[i].toInt()) {
      case 0:
        path.moveTo(_ops[i + 1], _ops[i + 2]);
        i += 3;
      case 1:
        path.lineTo(_ops[i + 1], _ops[i + 2]);
        i += 3;
      case 2:
        path.cubicTo(_ops[i + 1], _ops[i + 2], _ops[i + 3], _ops[i + 4], _ops[i + 5], _ops[i + 6]);
        i += 7;
      case 3:
        path.close();
        i += 1;
      default:
        // رسالةُ مطوّرٍ لا تُعرض — فبلا ترجمة.
        throw StateError('unknown path op at $i');
    }
  }
  return path;
}

